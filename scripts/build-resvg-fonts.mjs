// Regenerates src/lib/arimo-fonts.ts from src/assets/fonts/Arimo-{Regular,Bold}.ttf.
// The fonts are subset to Latin ranges (Spanish + common Latin American names) so the
// base64 payload stays small; Cloudflare Workers has no system fonts, so the renderer
// needs them embedded in the server bundle. License: SIL OFL 1.1 (src/assets/fonts/OFL-Arimo.txt).
// Run: node scripts/build-resvg-fonts.mjs
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const root = new URL("../", import.meta.url);

let text = "";
for (const [start, end] of [
  [0x20, 0x7e], // Basic Latin
  [0xa0, 0xff], // Latin-1 Supplement (á é í ó ú ñ ü ° ¿ ¡ etc.)
  [0x100, 0x17f], // Latin Extended-A
  [0x180, 0x24f], // Latin Extended-B
  [0x2000, 0x206f], // General Punctuation (– — “ ” ‘ ’ …)
  [0x20a0, 0x20bf], // Currency symbols (S/ € $ ¢)
  [0x2100, 0x214f], // Letterlike symbols (™ №)
]) {
  for (let cp = start; cp <= end; cp++) text += String.fromCodePoint(cp);
}

async function build(weight) {
  const ttf = await readFile(fileURLToPath(new URL(`src/assets/fonts/Arimo-${weight}.ttf`, root)));
  const subset = await subsetFont(ttf, text, {
    targetFormat: "sfnt",
    // keep family/subfamily names so fontdb can match "Arimo" and the bold weight
    preserveNameIds: [1, 2, 4, 6, 16, 17],
  });
  console.log(`Arimo ${weight}: ${(ttf.length / 1024) | 0}KB -> ${(subset.length / 1024) | 0}KB`);
  return Buffer.from(subset).toString("base64");
}

const [regular, bold] = await Promise.all([build("Regular"), build("Bold")]);

const out = `// Generated by scripts/build-resvg-fonts.mjs — do not edit by hand.
// Source: src/assets/fonts/Arimo-{Regular,Bold}.ttf (subset). License: SIL OFL 1.1, see src/assets/fonts/OFL-Arimo.txt.
export const ARIMO_REGULAR_B64 = "${regular}";
export const ARIMO_BOLD_B64 = "${bold}";
`;

await writeFile(fileURLToPath(new URL("src/lib/arimo-fonts.ts", root)), out);
console.log("wrote src/lib/arimo-fonts.ts");
