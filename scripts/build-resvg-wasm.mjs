// Regenerates src/lib/resvg-wasm.ts from node_modules/@resvg/resvg-wasm/index_bg.wasm.
// The .wasm is inlined as base64 because the ssr service bundle Nitro deploys for
// cloudflare-module is a lazy workerd module built with noExternal and no unwasm
// transform, so runtime .wasm imports are not resolvable there. Inlining keeps the
// bundle self-contained and identical between Node (vite dev) and Workers.
// Run: node scripts/build-resvg-wasm.mjs
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);

const wasm = await readFile(
  fileURLToPath(new URL("node_modules/@resvg/resvg-wasm/index_bg.wasm", root)),
);
const b64 = wasm.toString("base64");

const out = `// Generated by scripts/build-resvg-wasm.mjs — do not edit by hand.
// Source: node_modules/@resvg/resvg-wasm/index_bg.wasm (@resvg/resvg-wasm is MIT-licensed).
export const RESVG_WASM_B64 = "${b64}";
`;

await writeFile(fileURLToPath(new URL("src/lib/resvg-wasm.ts", root)), out);
console.log(`resvg wasm: ${(wasm.length / 1024) | 0}KB -> ${(b64.length / 1024) | 0}KB base64`);
